class Console {
public:
    Console() : handle_(::GetStdHandle(STD_OUTPUT_HANDLE)) {
        if (handle_ == NULL || handle_ == INVALID_HANDLE_VALUE)
            throw std::runtime_error("获取控制台句柄失败！");
    }

    // 代码页切到 UTF-8，保证中文正常显示
    void useUtf8() const {
        std::system("chcp 65001 > nul");
        ::SetConsoleOutputCP(CP_UTF8);
        ::SetConsoleCP(CP_UTF8);
    }

    // 设置字体（黑体，避免中文乱码）
    bool setFont(const wchar_t* faceName, SHORT width, SHORT height) const {
        CONSOLE_FONT_INFOEX info;
        std::memset(&info, 0, sizeof(info));
        info.cbSize     = sizeof(info);
        info.dwFontSize.X = width;
        info.dwFontSize.Y = height;
        std::wcsncpy(info.FaceName, faceName,
                     sizeof(info.FaceName) / sizeof(WCHAR) - 1);
        return ::SetCurrentConsoleFontEx(handle_, FALSE, &info) != FALSE;
    }

    // 打开 Windows 虚拟终端序列（ANSI 转义）支持
    void enableVirtualTerminal() const {
        DWORD mode = 0;
        if (!::GetConsoleMode(handle_, &mode))
            throw std::runtime_error("读取控制台模式失败！");
        if (!::SetConsoleMode(handle_, mode | ENABLE_VIRTUAL_TERMINAL_PROCESSING))
            throw std::runtime_error("无法开启终端虚拟序列支持！");
    }

    // 调整窗口大小
    void resize(int columns, int lines) const {
        char command[64];
        std::sprintf(command, "mode con cols=%d lines=%d", columns, lines);
        std::system(command);
    }

    void moveCursor(int x, int y) const {
        COORD coord;
        coord.X = static_cast<SHORT>(x);
        coord.Y = static_cast<SHORT>(y);
        ::SetConsoleCursorPosition(handle_, coord);
    }

    // 一次把整段内容写出去并刷新
    void write(const std::string& bytes) const {
        if (!bytes.empty())
            std::fwrite(bytes.data(), 1, bytes.size(), stdout);
        std::fflush(stdout);
    }

private:
    Console(const Console&);
    Console& operator=(const Console&);

    HANDLE handle_;
};

