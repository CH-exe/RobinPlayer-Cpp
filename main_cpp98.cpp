struct Pixel { unsigned char b, g, r; };   // 与 BMP 的 BGR 顺序一致

class Bitmap {
public:
    Bitmap() : width_(0), height_(0) {}

    int width() const  { return width_; }
    int height() const { return height_; }
    bool empty() const { return pixels_.empty(); }

    const Pixel& at(int x, int y) const {
        return pixels_[static_cast<std::size_t>(y) * width_ + x];
    }
    const Pixel& pixel(std::size_t index) const { return pixels_[index]; }
    std::size_t pixelCount() const { return pixels_.size(); }

    static Bitmap load(const char* path);

private:
    int width_;
    int height_;
    std::vector<Pixel> pixels_;
};

// 读取 24 位未压缩 BMP：行按 4 字节对齐，数据自下而上存放
Bitmap Bitmap::load(const char* path) {
    std::ifstream in(path, std::ios::binary);
    if (!in)
        throw std::runtime_error(std::string("无法打开图片文件：") + path);

    BITMAPFILEHEADER fileHeader;
    BITMAPINFOHEADER infoHeader;
    std::memset(&fileHeader, 0, sizeof(fileHeader));
    std::memset(&infoHeader, 0, sizeof(infoHeader));
    in.read(reinterpret_cast<char*>(&fileHeader), sizeof(fileHeader));
    in.read(reinterpret_cast<char*>(&infoHeader), sizeof(infoHeader));
    if (!in)
        throw std::runtime_error(std::string("BMP 文件头不完整：") + path);

    if (fileHeader.bfType != 0x4D42)                     // 'BM'
        throw std::runtime_error(std::string("不是有效的 BMP 文件：") + path);
    if (infoHeader.biBitCount != 24 || infoHeader.biCompression != BI_RGB)
        throw std::runtime_error(std::string("只支持 24 位未压缩的 BMP：") + path);

    const bool topDown = infoHeader.biHeight < 0;
    const int width  = static_cast<int>(infoHeader.biWidth);
    const int height = topDown ? -static_cast<int>(infoHeader.biHeight)
                               : static_cast<int>(infoHeader.biHeight);
    if (width <= 0 || height <= 0)
        throw std::runtime_error(std::string("BMP 尺寸无效：") + path);

    const std::size_t rowStride =
        (static_cast<std::size_t>(width) * 3 + 3) / 4 * 4;
    std::vector<unsigned char> raw(rowStride * static_cast<std::size_t>(height));

    in.seekg(static_cast<std::streamoff>(fileHeader.bfOffBits), std::ios::beg);
    in.read(reinterpret_cast<char*>(&raw[0]),
            static_cast<std::streamsize>(raw.size()));
    if (!in)
        throw std::runtime_error(std::string("BMP 像素数据不完整：") + path);

    Bitmap bitmap;
    bitmap.width_  = width;
    bitmap.height_ = height;
    bitmap.pixels_.resize(static_cast<std::size_t>(width) *
                          static_cast<std::size_t>(height));

    for (int y = 0; y < height; ++y) {
        const int sourceRow = topDown ? y : height - 1 - y;
        const unsigned char* source =
            &raw[rowStride * static_cast<std::size_t>(sourceRow)];
        std::memcpy(&bitmap.pixels_[static_cast<std::size_t>(y) * width],
                    source, static_cast<std::size_t>(width) * sizeof(Pixel));
    }
    return bitmap;
}

