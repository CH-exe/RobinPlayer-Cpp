// ===========================================================================
//  Base64 解码
// ===========================================================================
int base64Value(char c) {
    if (c >= 'A' && c <= 'Z') return c - 'A';
    if (c >= 'a' && c <= 'z') return c - 'a' + 26;
    if (c >= '0' && c <= '9') return c - '0' + 52;
    if (c == '+') return 62;
    if (c == '/') return 63;
    return -1;
}

// 标准 Base64（带 '=' 填充），跳过换行、空格等无关字符
std::vector<unsigned char> base64Decode(const char* text, std::size_t length) {
    std::vector<unsigned char> out;
    out.reserve(length / 4 * 3 + 3);

    unsigned int buffer = 0;
    int bits = 0;

    for (std::size_t i = 0; i < length; ++i) {
        const char ch = text[i];
        if (ch == '=') break;            // 填充之后没有数据了
        const int value = base64Value(ch);
        if (value < 0) continue;         // 忽略无关字符

        buffer = (buffer << 6) | static_cast<unsigned int>(value);
        bits += 6;
        if (bits >= 8) {
            bits -= 8;
            out.push_back(static_cast<unsigned char>((buffer >> bits) & 0xFFU));
        }
    }
    return out;
}

