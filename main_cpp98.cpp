struct EmbeddedAsset {
    const char* fileName;
    const char* base64;
    std::size_t base64Length;
};

const EmbeddedAsset kAssets[] = {
    { kMusicPath, kMusicBase64, sizeof(kMusicBase64) - 1 },
    { kLyricPath, kLyricBase64, sizeof(kLyricBase64) - 1 },
    { kPic1Path,  kPic1Base64,  sizeof(kPic1Base64)  - 1 },
    { kPic2Path,  kPic2Base64,  sizeof(kPic2Base64)  - 1 },
};

bool fileExists(const char* path) {
    return ::GetFileAttributesA(path) != INVALID_FILE_ATTRIBUTES;
}

// 把四段 Base64 解成文件；已存在的文件不覆盖（和原程序一致）
void extractAssets() {
    for (std::size_t i = 0; i < sizeof(kAssets) / sizeof(kAssets[0]); ++i) {
        const EmbeddedAsset& asset = kAssets[i];
        if (fileExists(asset.fileName))
            continue;

        std::vector<unsigned char> bytes =
            base64Decode(asset.base64, asset.base64Length);
        if (bytes.empty())
            throw std::runtime_error(std::string("内嵌数据损坏：") + asset.fileName);

        std::ofstream out(asset.fileName, std::ios::binary | std::ios::trunc);
        if (!out)
            throw std::runtime_error(std::string("写入文件时出错：") + asset.fileName);

        out.write(reinterpret_cast<const char*>(&bytes[0]),
                  static_cast<std::streamsize>(bytes.size()));
        if (!out)
            throw std::runtime_error(std::string("写入文件时出错：") + asset.fileName);
    }
}

